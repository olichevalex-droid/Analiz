def bubble_sort(items):
    """Сортировка пузырьком.

    Идём по списку и меняем местами соседей, если они стоят неправильно.
    После каждого прохода самое большое число "всплывает" в конец.
    Возвращает новый отсортированный список, исходный не меняется.
    """
    arr = list(items)  # копия, чтобы не портить оригинал
    n = len(arr)
    for i in range(n):
        swapped = False
        # последние i элементов уже на своих местах
        for j in range(n - 1 - i):
            if arr[j] > arr[j + 1]:
                arr[j], arr[j + 1] = arr[j + 1], arr[j]
                swapped = True
        if not swapped:  # за проход ничего не поменяли, значит всё готово
            break
    return arr
